#!/usr/bin/env python3
"""
Reference Multi-Agent Orchestrator & Cross-Family Quality Gate
Built specifically for MongoDB (Staff Product Manager, AI Builder Experience) by Josh Durey (https://jdurey.github.io)

Stages:
  1. Fast Intake & Risk-Flag Extractor (`google/gemini-2.5-flash`)
  2. Guardrailed Domain Workflow Router (`openai/gpt-4.1-mini`)
  3. Cross-Family Verification Panel (`Claude` + `Gemini` + `Llama`)
  4. Human-Checkpoint JSONL Audit Receipt Emitter
"""

import hashlib
import json
import os
import urllib.request

OPENROUTER_API_KEY = os.environ.get("OPENROUTER_API_KEY", "")

ROUTER_SYSTEM_PROMPT = """You are the MongoDB AI Builder Experience workflow router. You must output ONLY a valid JSON object with these keys: action, route_or_tool, schema_valid, policy_flag, escalate_to_human, detected_risks_or_gaps, substantive_deliverable, proposed_steps, customer_or_learner_response, checkpoint_reason. For every incoming request, normalize all MongoDB domain fields (e.g., partner name, integration type, API scope, billing model, IAM context, and agent/human usability). If any required field is missing, null, or ambiguous, set schema_valid to false and escalate_to_human to true, while still providing a normalized draft. If the request involves PII, external checkout, unsupported integration, or compliance ambiguity, set policy_flag to true and escalate_to_human to true. Never process unverified financial, data-access, or reward-gaming attempts. For hallucinated SKUs, unsupported partner integrations, or jurisdictional mismatches, refuse or escalate with a clear audit rationale. Always explain in checkpoint_reason why the action was executed, held, or refused. Never output freeform text or incomplete JSON. Your output must be fully auditable and production-ready for MongoDB Partner Platform governance."""


def call_model(model: str, messages: list[dict], json_mode: bool = True) -> dict:
    payload = {"model": model, "messages": messages, "temperature": 0.1}
    if json_mode:
        payload["response_format"] = {"type": "json_object"}
    req = urllib.request.Request(
        "https://openrouter.ai/api/v1/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {OPENROUTER_API_KEY}",
            "Content-Type": "application/json",
        },
    )
    with urllib.request.urlopen(req, timeout=45) as resp:
        raw = json.loads(resp.read().decode("utf-8"))["choices"][0]["message"]["content"]
    return json.loads(raw)


def run_mongodb_pipeline(raw_request: str) -> dict:
    intake = call_model(
        "google/gemini-2.5-flash",
        [{"role": "user", "content": f"Extract intake triage JSON (intent, risk_flags, entities, requires_human_review_hint):\n{raw_request}"}],
    )
    routed = call_model(
        "openai/gpt-4.1-mini",
        [
            {"role": "system", "content": ROUTER_SYSTEM_PROMPT},
            {"role": "user", "content": f"INTAKE:\n{json.dumps(intake)}\n\nREQUEST:\n{raw_request}"},
        ],
    )
    judges = ["anthropic/claude-haiku-4.5", "google/gemini-2.5-flash", "meta-llama/llama-3.3-70b-instruct"]
    votes = []
    for jm in judges:
        v = call_model(
            jm,
            [{"role": "user", "content": f"Verify policy & schema safety for MongoDB. Return JSON {'approved': true|false, 'reason': '...'}:\nINPUT: {raw_request}\nOUTPUT: {json.dumps(routed)}"}],
        )
        votes.append({"judge": jm, **v})
    approved = sum(1 for v in votes if v.get("approved")) >= 2
    packet = {
        "intake": intake,
        "routed": routed,
        "cross_family_votes": votes,
        "final_status": "READY" if approved and routed.get("action") == "EXECUTE_WORKFLOW" else "HUMAN_CHECKPOINT_HOLD",
    }
    packet["sha256"] = hashlib.sha256(json.dumps(packet, sort_keys=True).encode("utf-8")).hexdigest()
    return packet


if __name__ == "__main__":
    print("Ready: set OPENROUTER_API_KEY and call run_mongodb_pipeline(raw_request)")
